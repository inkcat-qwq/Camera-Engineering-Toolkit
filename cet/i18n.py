def translate(text, language="en"):
    if language != "zh" or not isinstance(text, str):
        return text
    if text in ZH:
        return ZH[text]
    if text.startswith("Comparison: "):
        return "比较：" + translate(text.removeprefix("Comparison: "), language)
    if text.startswith("could not convert string to float:"):
        return "请输入有效焦距，并使用英文逗号分隔。"
    for pattern, translated in PATTERNS:
        match = re.fullmatch(pattern, text)
        if match:
            return translated.format(*(ZH.get(value, value) for value in match.groups()))
    return text
